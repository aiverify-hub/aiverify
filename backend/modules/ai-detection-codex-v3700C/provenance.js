'use strict';

const MODULE_VERSION = 'AI_DETECTION_PROVENANCE_V1_CODEX_BATCH5';

const EXPLICIT_DISCLOSURE_PATTERNS = Object.freeze([
  { label: 'C2PA or Content Credentials text (not a verified manifest)', regex: /\bc2pa\b|content credentials?/i },
  { label: 'AI-disclosure text (may be negated or quoted)', regex: /\b(?:ai[- ]generated|generated by ai|synthetic media|synthetically generated)\b/i },
  { label: 'Adobe Firefly disclosure', regex: /\badobe firefly\b/i }
]);

const AI_TOOL_PATTERNS = Object.freeze([
  { label: 'DALL-E or OpenAI image marker', regex: /\bdall[- ]?e\b|\bopenai image\b/i },
  { label: 'Midjourney marker', regex: /\bmidjourney\b/i },
  { label: 'Stable Diffusion marker', regex: /\bstable diffusion\b|\bautomatic1111\b|\bcomfyui\b/i },
  { label: 'Runway marker', regex: /\brunway(?:ml)?\b/i },
  { label: 'Sora marker', regex: /\bopenai sora\b|\bsora video\b/i },
  { label: 'Pika marker', regex: /\bpika(?: labs)?\b/i },
  { label: 'Leonardo AI marker', regex: /\bleonardo\.?ai\b/i },
  { label: 'Ideogram marker', regex: /\bideogram\b/i },
  { label: 'FLUX model marker', regex: /\bflux(?:\.1)?\b[^\r\n]{0,30}\b(?:model|schnell|dev|pro)\b/i }
]);

function searchableText(buffer) {
  const latin = buffer.toString('latin1');
  const utf8 = buffer.toString('utf8');
  return (latin + '\n' + utf8).replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]+/g, ' ');
}

function collectMatches(text, patterns) {
  const matches = [];
  patterns.forEach(function (entry) {
    if (entry.regex.test(text)) matches.push(entry.label);
  });
  return matches;
}

function inspect(preparedMedia) {
  if (!preparedMedia || !Buffer.isBuffer(preparedMedia.buffer)) {
    throw new Error('AI provenance inspection requires validated media bytes.');
  }
  const text = searchableText(preparedMedia.buffer);
  const explicit = collectMatches(text, EXPLICIT_DISCLOSURE_PATTERNS);
  const tools = collectMatches(text, AI_TOOL_PATTERNS);
  const signals = explicit.concat(tools).filter(function (value, index, list) {
    return list.indexOf(value) === index;
  }).slice(0, 10);

  const status = signals.length ? 'UNVERIFIED_METADATA_MARKERS' : 'NO_PROVENANCE_EVIDENCE';
  const answer = signals.length ? 'Unverified text or metadata markers were found.' : 'No provenance evidence was found.';
  const explanation = 'Raw strings do not establish a creation history or authenticate a provenance assertion. This build does not parse or cryptographically verify provenance manifests. Missing markers do not prove human creation.';
  return Object.freeze({
    version: MODULE_VERSION,
    status: status,
    answer: answer,
    explanation: explanation,
    signals: Object.freeze(signals),
    evidenceKind: signals.length ? 'UNVERIFIED_MARKERS' : 'INSUFFICIENT_EVIDENCE',
    assertions: Object.freeze([]),
    assertionExtractionSupported: false,
    verificationSupported: false,
    verified: false,
    visualOrAudioContentAnalyzed: false,
    metadataOnly: true
  });
}

module.exports = Object.freeze({
  MODULE_VERSION: MODULE_VERSION,
  inspect: inspect
});
